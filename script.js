function setStats(members,online){

  const membersEl=
    document.querySelector('#members');

  const onlineEl=
    document.querySelector('#online');

  if(
    Number.isFinite(members) &&
    membersEl
  ){
    membersEl.textContent=
      members.toLocaleString();
  }

  if(
    Number.isFinite(online) &&
    onlineEl
  ){
    onlineEl.textContent=
      online.toLocaleString();
  }
}


async function stats(){

  const inviteUrl=
    CONFIG.INVITE_URL||'';

  const inviteMatch=
    inviteUrl.match(
      /discord(?:\.gg|\.com\/invite)\/([^/?#]+)/i
    );

  const inviteCode=
    inviteMatch?.[1];


  if(inviteCode){

    try{

      const r=await fetch(
        `https://discord.com/api/v10/invites/${encodeURIComponent(inviteCode)}?with_counts=true`,
        {
          headers:{
            Accept:'application/json'
          }
        }
      );


      if(r.ok){

        const d=await r.json();

        setStats(
          d.approximate_member_count,
          d.approximate_presence_count
        );

        return;
      }

    }catch(e){}
  }


  if(
    !CONFIG.SERVER_ID ||
    CONFIG.SERVER_ID.includes('REPLACE')
  ){
    return;
  }


  try{

    const r=await fetch(
      `https://discord.com/api/guilds/${encodeURIComponent(CONFIG.SERVER_ID)}/widget.json`,
      {
        headers:{
          Accept:'application/json'
        }
      }
    );


    if(!r.ok){
      throw new Error(
        'Discord widget request failed'
      );
    }


    const d=await r.json();

    setStats(
      undefined,
      d.presence_count
    );

  }catch(e){}
}


stats();
