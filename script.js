function renderChannel(id=currentChannel){
  const item=document.querySelector(`.channelItem[data-channel="${id}"]`);
  const bg=document.querySelector('#channelPreviewBg');
  const number=document.querySelector('#channelPreviewNumber');
  const title=document.querySelector('#channelPreviewTitle');
  const text=document.querySelector('#channelPreviewText');

  if(!item||!bg||!number||!title||!text)return;

  currentChannel=id;

  document.querySelectorAll('.channelItem').forEach(btn=>{
    const active=btn.dataset.channel===id;
    btn.classList.toggle('active',active);
    btn.setAttribute('aria-selected',active?'true':'false');
  });

  const key=`guide.${id}`;

  number.textContent=id;
  title.textContent=I18N[currentLanguage][`${key}.name`];
  text.innerHTML=I18N[currentLanguage][`${key}.text`];

  bg.style.backgroundImage=`url("${CHANNELS[id].bg}")`;
}

function applyLanguage(lang){
  currentLanguage=I18N[lang]?lang:'ja';

  const dict=I18N[currentLanguage];

  document.documentElement.lang=currentLanguage==='ja'?'ja':'en';

  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key=el.dataset.i18n;

    if(dict[key]!==undefined)el.innerHTML=dict[key];
  });

  document.querySelectorAll('.langBtn').forEach(btn=>{
    btn.classList.toggle('active',btn.dataset.lang===currentLanguage);
  });

  localStorage.setItem('wuwa-language',currentLanguage);

  renderChannel(currentChannel);
}

