function openGalleryLightbox(src,alt=''){

  const existing=
    document.querySelector('.galleryLightbox');

  if(existing){
    existing.remove();
  }


  const modal=document.createElement('div');

  modal.className='galleryLightbox';

  modal.innerHTML=`
    <button
      class="galleryLightboxClose"
      type="button"
      aria-label="Close"
    >×</button>

    <img
      src="${src}"
      alt="${alt.replace(/"/g,'&quot;')}"
    >
  `;


  document.body.appendChild(modal);


  requestAnimationFrame(()=>{
    modal.classList.add('visible');
  });


  const close=()=>{

    modal.classList.remove('visible');

    setTimeout(()=>{
      modal.remove();
    },180);
  };


  modal.addEventListener('click',e=>{

    if(
      e.target===modal ||
      e.target.closest('.galleryLightboxClose')
    ){
      close();
    }
  });


  modal
    .querySelector('img')
    .addEventListener('click',e=>{
      e.stopPropagation();
    });


  const esc=e=>{

    if(e.key==='Escape'){

      close();

      document.removeEventListener(
        'keydown',
        esc
      );
    }
  };


  document.addEventListener(
    'keydown',
    esc
  );
}


