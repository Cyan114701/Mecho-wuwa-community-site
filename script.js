// Gallery
// 最大30枚まで対応。
// 30枚未満でも登録されている画像を自動複製して無限ループ。
// ============================================================

const galleryViewport=document.querySelector('.galleryViewport');
const galleryTrack=document.querySelector('#galleryTrack');

if(galleryViewport && galleryTrack){

  // HTMLに登録されている画像を最大30枚まで取得。
  const originalImages=[
    ...galleryTrack.querySelectorAll('img')
  ].slice(0,30);

  if(originalImages.length){

    // 1セット目
    const firstSet=document.createElement('div');
    firstSet.className='gallerySet';

    // 2セット目
    // 1セット目と同じ画像を複製して、
    // 画面外に出たとき自然に1セット目へ戻れるようにする。
    const secondSet=document.createElement('div');
    secondSet.className='gallerySet';

    originalImages.forEach(img=>{
      firstSet.appendChild(img);
    });

    originalImages.forEach(img=>{
      const clone=img.cloneNode(true);

      // 2セット目はスクリーンリーダーから重複して認識されないようにする。
      clone.setAttribute('aria-hidden','true');

      secondSet.appendChild(clone);
    });

    // 元のgalleryTrackを2セット構成に置き換える。
    galleryTrack.replaceChildren(firstSet,secondSet);


    let offset=0;
    let lastTime=performance.now();

    let dragging=false;
    let dragStartX=0;
    let dragStartOffset=0;
    let moved=false;

    // 1セット分の横幅。
    let setWidth=0;

    // 自動スクロール速度。
    // 数値を大きくすると速く、小さくすると遅くなる。
    const speed=41.8;


    // --------------------------------------------------------
    // ギャラリー1セット分の幅を計測
    // --------------------------------------------------------
    function measure(){

      setWidth=firstSet.getBoundingClientRect().width;

      if(setWidth>0){

        // offsetを1セット内に収める。
        offset=((offset%setWidth)+setWidth)%setWidth;

        galleryTrack.style.transform=
          `translate3d(${-offset}px,0,0)`;
      }
    }


    // --------------------------------------------------------
    // ループ位置を正規化
    // --------------------------------------------------------
    function normalize(){

      if(setWidth<=0)return;

      while(offset>=setWidth){
        offset-=setWidth;
      }

      while(offset<0){
        offset+=setWidth;
      }
    }


    // --------------------------------------------------------
    // 自動スクロール
    // --------------------------------------------------------
    function animate(now){

      const dt=Math.min(
        (now-lastTime)/1000,
        0.05
      );

      lastTime=now;

      if(!dragging){

        offset+=speed*dt;

        normalize();

        galleryTrack.style.transform=
          `translate3d(${-offset}px,0,0)`;
      }

      requestAnimationFrame(animate);
    }


    // --------------------------------------------------------
    // ドラッグ開始
    // --------------------------------------------------------
    galleryViewport.addEventListener('pointerdown',e=>{

      if(e.button!==0)return;

      dragging=true;
      moved=false;

      dragStartX=e.clientX;
      dragStartOffset=offset;

      galleryViewport.classList.add('is-dragging');

      galleryViewport.setPointerCapture?.(e.pointerId);
    });


    // --------------------------------------------------------
    // ドラッグ中
    // --------------------------------------------------------
    galleryViewport.addEventListener('pointermove',e=>{

      if(!dragging)return;

      const dx=e.clientX-dragStartX;

      if(Math.abs(dx)>5){
        moved=true;
      }

      offset=dragStartOffset-dx;

      normalize();

      galleryTrack.style.transform=
        `translate3d(${-offset}px,0,0)`;
    });


    // --------------------------------------------------------
    // ドラッグ終了
    // --------------------------------------------------------
    const endDrag=e=>{

      if(!dragging)return;

      dragging=false;

      galleryViewport.classList.remove('is-dragging');

      try{
        galleryViewport.releasePointerCapture?.(e.pointerId);
      }catch(_){}
    };


    galleryViewport.addEventListener(
      'pointerup',
      endDrag
    );

    galleryViewport.addEventListener(
      'pointercancel',
      endDrag
    );


    // --------------------------------------------------------
    // クリックとドラッグを区別
    // --------------------------------------------------------
    let suppressClick=false;

    galleryViewport.addEventListener('pointerup',e=>{

      if(e.button!==0)return;

      suppressClick=moved;
    });


    // --------------------------------------------------------
    // 画像クリック → Lightbox
    // --------------------------------------------------------
    galleryViewport.addEventListener('click',e=>{

      const img=e.target.closest('img');

      if(!img)return;

      // ドラッグ操作だった場合はLightboxを開かない。
      if(suppressClick){

        e.preventDefault();
        e.stopPropagation();

        suppressClick=false;

        return;
      }

      openGalleryLightbox(
        img.currentSrc||img.src,
        img.alt
      );
    });


    // --------------------------------------------------------
    // ウィンドウサイズ変更時に再計測
    // --------------------------------------------------------
    window.addEventListener(
      'resize',
      measure
    );

    window.addEventListener(
      'load',
      measure
    );


    // --------------------------------------------------------
    // 初期化
    // --------------------------------------------------------
    requestAnimationFrame(()=>{

      measure();

      requestAnimationFrame(animate);
    });

  }
}


